"""Tests for ziro config set command (Spec 006 R4, Phase 6f).

Verifies setting configuration options, validation against known categories,
and regeneration of derived shell scripts when applicable.
"""

from __future__ import annotations

import tempfile
import unittest
from pathlib import Path
from unittest import mock

from core import config_cli

import pytest
pytestmark = pytest.mark.unit


class TestConfigSet(unittest.TestCase):
    def test_config_set_prompt_default_updates_defaults_toml(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            cfg = Path(tmp)
            with mock.patch.dict("os.environ", {"ZIRO_CONFIG": str(cfg)}):
                rc = config_cli.main(["set", "prompt.default", "pure"])
            self.assertEqual(rc, 0)

            defaults_file = cfg / "defaults.toml"
            self.assertTrue(defaults_file.is_file())
            content = defaults_file.read_text()
            self.assertIn("[prompt]", content)
            self.assertIn('default = "pure"', content)

    def test_config_set_flat_key_prompt(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            cfg = Path(tmp)
            with mock.patch.dict("os.environ", {"ZIRO_CONFIG": str(cfg)}):
                rc = config_cli.main(["set", "prompt", "starship"])
            self.assertEqual(rc, 0)
            content = (cfg / "defaults.toml").read_text()
            self.assertIn('default = "starship"', content)

    def test_config_set_unknown_category_error(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            cfg = Path(tmp)
            with mock.patch.dict("os.environ", {"ZIRO_CONFIG": str(cfg)}):
                rc = config_cli.main(["set", "unknown_category.foo", "bar"])
            self.assertEqual(rc, 2)

    def test_config_set_invalid_prompt_value_error(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            cfg = Path(tmp)
            with mock.patch.dict("os.environ", {"ZIRO_CONFIG": str(cfg)}):
                rc = config_cli.main(["set", "prompt.default", "unsupported_prompt_engine"])
            self.assertEqual(rc, 2)

    def test_config_set_regenerates_plugins_gen_zsh(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            cfg = Path(tmp)
            with mock.patch.dict("os.environ", {"ZIRO_CONFIG": str(cfg)}):
                rc = config_cli.main(["set", "prompt.default", "starship"])
            self.assertEqual(rc, 0)

            derived_file = cfg / "derived" / "plugins.gen.zsh"
            self.assertTrue(derived_file.is_file())
            self.assertIn("AUTO-GENERATED by ziro", derived_file.read_text())


if __name__ == "__main__":
    unittest.main()
