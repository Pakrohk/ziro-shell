"""Write a load.toml dict back to disk, preserving [user] verbatim.

Pure Python stdlib. Handles [[tool]] arrays, [meta], [boot], [defer], [user].
"""
import os
import tomllib
from pathlib import Path


def _quote(v):
    if isinstance(v, str):
        return '"' + v.replace('"', '\\"') + '"'
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return str(v)
    return '"' + str(v) + '"'


def _write_section(f, name, data):
    f.write(f"\n[{name}]\n")
    for k, v in data.items():
        if isinstance(v, list) and all(isinstance(x, str) for x in v):
            f.write(f"{k} = [{', '.join(_quote(x) for x in v)}]\n")
        elif isinstance(v, list):
            f.write(f"{k} = [\n")
            for item in v:
                f.write(f"  {_quote(item)},\n")
            f.write("]\n")
        elif isinstance(v, dict):
            parts = [f"{kk} = {_quote(vv)}" for kk, vv in v.items()]
            f.write(f"{k} = {{ {', '.join(parts)} }}\n")
        else:
            f.write(f"{k} = {_quote(v)}\n")


def write_load_toml(data: dict, path: str) -> None:
    """Write load.toml dict to path. Order: meta, boot, defer, [[tool]], [user]."""
    p = Path(path).expanduser()
    p.parent.mkdir(parents=True, exist_ok=True)

    with p.open("w", encoding="utf-8") as f:
        f.write("# ~/.config/ziro/load.toml — generated by `ziro analyze`\n")
        f.write("# Edit [user] section to customize. Run `ziro sync` after editing.\n")
        f.write("# Run `ziro analyze --full` to regenerate [[tool]] entries from scratch.\n\n")

        for section in ("meta", "boot", "defer"):
            if section in data:
                _write_section(f, section, data[section])

        for tool in data.get("tool", []):
            f.write("\n[[tool]]\n")
            for k, v in tool.items():
                if isinstance(v, list):
                    if k == "trigger_keys":
                        f.write(f"{k} = [\n")
                        for item in v:
                            if isinstance(item, dict):
                                parts = [f"{kk} = {_quote(vv)}" for kk, vv in item.items()]
                                f.write(f"  {{ {', '.join(parts)} }},\n")
                            else:
                                f.write(f"  {_quote(item)},\n")
                        f.write("]\n")
                    else:
                        f.write(f"{k} = [{', '.join(_quote(x) for x in v)}]\n")
                elif isinstance(v, dict):
                    parts = [f"{kk} = {_quote(vv)}" for kk, vv in v.items()]
                    f.write(f"{k} = {{ {', '.join(parts)} }}\n")
                else:
                    f.write(f"{k} = {_quote(v)}\n")

        if "user" in data:
            f.write("\n[user]\n")
            user = data["user"]
            if isinstance(user, dict):
                if not user:
                    f.write("# User decisions that survive `ziro analyze --full`\n")
                elif "override" in user and isinstance(user["override"], list):
                    for entry in user["override"]:
                        f.write("\n[[user.override]]\n")
                        for k, v in entry.items():
                            if isinstance(v, list):
                                if k == "trigger_keys":
                                    f.write(f"{k} = [\n")
                                    for item in v:
                                        if isinstance(item, dict):
                                            parts = [f"{kk} = {_quote(vv)}" for kk, vv in item.items()]
                                            f.write(f"  {{ {', '.join(parts)} }},\n")
                                        else:
                                            f.write(f"  {_quote(item)},\n")
                                    f.write("]\n")
                                else:
                                    f.write(f"{k} = [{', '.join(_quote(x) for x in v)}]\n")
                            else:
                                f.write(f"{k} = {_quote(v)}\n")
                else:
                    for k, v in user.items():
                        f.write(f"{k} = {_quote(v)}\n")


def load_external_overrides(path: str = None) -> dict:
    """Load external overrides file (optional). Returns dict or empty dict.

    Path resolution: explicit arg > $ZIRO_OVERRIDES_FILE > ~/.config/ziro/overrides.toml
    Format: same as [user] section in load.toml (TOML, with [[user.override]] or [[override]]).
    """
    if path is None:
        path = os.environ.get(
            "ZIRO_OVERRIDES_FILE",
            str(Path.home() / ".config" / "ziro" / "overrides.toml"),
        )
    f = Path(path).expanduser()
    if not f.is_file():
        return {}
    try:
        with f.open("rb") as fp:
            data = tomllib.load(fp)
        return data
    except Exception:
        return {}
