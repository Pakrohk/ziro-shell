def get_completion_data() -> dict[str, Any]:
    """Extract structured command, subcommand, and flag completion data from HELP_REGISTRY."""
    top_commands: list[tuple[str, str]] = []
    subcommands_map: dict[str, list[tuple[str, str]]] = {}
    flags_map: dict[str, list[tuple[str, str]]] = {}

    for name, entry in HELP_REGISTRY.items():
        if " " not in name:
            top_commands.append((name, entry.summary))
            if entry.subcommands:
                subcommands_map[name] = [
                    (sub, desc) for sub, desc in entry.subcommands.items()
                ]
            if entry.flags:
                flags_map[name] = [(f[0], f[1]) for f in entry.flags]
        else:
            # Subcommand entry, e.g. "plugin add"
            if entry.flags:
                flags_map[name] = [(f[0], f[1]) for f in entry.flags]

    top_commands.sort(key=lambda x: x[0])
    return {
        "commands": top_commands,
        "subcommands": subcommands_map,
        "flags": flags_map,
    }


def _escape_zsh_desc(desc: str) -> str:
    """Escape brackets and colons for zsh _describe / _arguments."""
    return desc.replace(":", "\\:").replace("[", "\\[").replace("]", "\\]").replace("'", "'\\''")


