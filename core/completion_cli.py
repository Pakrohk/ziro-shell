def cmd_completion(argv: list[str] | None = None) -> int:
    """Entry point for `ziro completion [shell]`."""
    from core.help_cli import handle_help_if_requested
    ret = handle_help_if_requested(argv, "completion")
    if ret is not None:
        return ret

    raw_args = argv or []
    if "--rebuild" in raw_args:
        from core.paths import get_paths
        p = get_paths()["data"] / "completions" / "_ziro"
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(generate_zsh_completion(), encoding="utf-8")
        print(f"✅ completion script updated: {p}")
        return 0

    args = [a for a in raw_args if not a.startswith("-")]
    shell = args[0] if args else "zsh"

    if shell != "zsh":
        print(f"ziro completion: unsupported shell '{shell}'. Supported: zsh", file=sys.stderr)
        return 1

    print(generate_zsh_completion())
    return 0


def main(argv: list[str]) -> int:
    return cmd_completion(argv)


