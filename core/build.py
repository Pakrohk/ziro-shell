def load_manifest(load_toml_path: Path) -> dict[str, Any]:
    """Load and parse load.toml."""
    if not load_toml_path.is_file():
        load_toml_path.parent.mkdir(parents=True, exist_ok=True)
        load_toml_path.write_text(default_manifest_content(), encoding="utf-8")

    with load_toml_path.open("rb") as f:
        return tomllib.load(f)


def validate_manifest(data: dict[str, Any]) -> list[str]:
    """Validate load.toml schema and semantic invariants.

    Returns a list of error strings; empty list indicates success.
    """
    errors: list[str] = []

    for sec in ("meta", "boot", "defer"):
        if sec not in data:
            errors.append(f"Missing required section: [{sec}]")

    tools = data.get("tool", [])
    if not isinstance(tools, list):
        errors.append("[[tool]] must be an array of tables")
        return errors

    seen_names: set[str] = set()
    active_tools: set[str] = set()

    for idx, t in enumerate(tools):
        name = t.get("name")
        if not name or not isinstance(name, str):
            errors.append(f"Tool at index {idx} missing valid 'name'")
            continue
        if name in seen_names:
            errors.append(f"Duplicate tool name: '{name}'")
        seen_names.add(name)

        if t.get("enabled", True):
            active_tools.add(name)

        timing = t.get("timing")
        if timing not in ("eager", "deferred", "on-demand"):
            errors.append(f"Tool '{name}' has invalid timing: '{timing}' (expected eager/deferred/on-demand)")

        method = t.get("method")
        if method not in ("source", "eval-cache", "builtin", "local-source"):
            errors.append(f"Tool '{name}' has invalid method: '{method}'")

        order = t.get("order")
        if order is not None and not isinstance(order, int):
            errors.append(f"Tool '{name}' order must be integer, got {type(order).__name__}")

    # Check conflicts between active tools
    for t in tools:
        if not t.get("enabled", True):
            continue
        conflicts = t.get("conflicts_with", [])
        for conf in conflicts:
            if conf in active_tools:
                errors.append(f"Conflict detected: '{t.get('name')}' conflicts with active tool '{conf}'")

    return errors


def apply_overrides(
    tools: list[dict[str, Any]],
    user_section: dict[str, Any] | None,
    external_override_path: Path | None = None,
) -> list[dict[str, Any]]:
    """Apply user overrides to tools list.

    Priority: External override file > [user] section in load.toml > tool defaults.
    """
    merged_tools = [dict(t) for t in tools]
    by_name = {t["name"]: t for t in merged_tools}

    # 1. Apply [user.override]
    if user_section:
        overrides = user_section.get("override", [])
        if isinstance(overrides, list):
            for ov in overrides:
                name = ov.get("name")
                if name in by_name:
                    for k, v in ov.items():
                        if k not in ("name", "reason"):
                            by_name[name][k] = v

    # 2. Apply external override file if present
    if external_override_path and external_override_path.is_file():
        try:
            with external_override_path.open("rb") as f:
                ext_data = tomllib.load(f)
                ext_overrides = ext_data.get("override", ext_data.get("user", {}).get("override", []))
                for ov in ext_overrides:
                    name = ov.get("name")
                    if name in by_name:
                        for k, v in ov.items():
                            if k not in ("name", "reason"):
                                by_name[name][k] = v
        except Exception as e:
            print(f"ziro sync: warning reading external override: {e}", file=sys.stderr)

    return merged_tools


