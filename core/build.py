def render_boot_script(
    manifest: dict[str, Any],
    tools: list[dict[str, Any]],
    defer_root: Path,
) -> str:
    """Compose full flattened ziro-boot.zsh script."""
    defer_sec = manifest.get("defer", {})
    eager_mods = defer_sec.get("eager_modules", DEFAULT_EAGER_MODULES)

    now_iso = datetime.now(timezone.utc).isoformat()
    header = [
        "# AUTO-GENERATED by ziro sync — do not edit directly",
        f"# Generated: {now_iso}",
        "# Schema: 1.0.0 · Post-Integration Pipeline",
        "emulate -L zsh",
    ]

    parts = [
        "\n".join(header),
        render_defer_core(defer_root, eager_mods),
        render_eager_section(tools),
        render_deferred_section(tools),
        render_ondemand_section(tools),
        render_cli_section(),
        render_finalize_section(),
    ]

    return "\n\n".join(parts) + "\n"


def compile_zwc(script_path: Path) -> tuple[bool, str]:
    """Compile ziro-boot.zsh into .zwc using Zsh zcompile."""
    cmd = f"zcompile -U -M '{script_path}' && zcompile -U -M '{script_path.with_suffix('.zwc')}' '{script_path}'"
    r = subprocess.run(
        ["zsh", "-c", cmd],
        capture_output=True,
        text=True,
        timeout=15,
    )
    if r.returncode != 0:
        return False, r.stderr.strip()
    return True, ""


def _run_zcompile(files: list[str], timeout_s: int = 30) -> dict[str, Any]:
    """Run zcompile on multiple .zsh files in one shell invocation.
    Returns {'compiled': [...], 'skipped': [...], 'errors': [(path, msg)]}.
    Non-fatal: always returns a dict, never raises. Missing .zwc after run
    is recorded as error but build continues.
    """
    result: dict[str, Any] = {"compiled": [], "skipped": [], "errors": []}
    existing: list[str] = []
    for f in files:
        fpath = Path(os.path.expandvars(os.path.expanduser(f)))
        if not fpath.is_file():
            result["skipped"].append(str(fpath))
            continue
        existing.append(str(fpath))

    if not existing:
        return result

    # Single fork: compile each file in-place
    cmd = "for f in " + " ".join(f"'{p}'" for p in existing) + '; do zcompile -U -M "$f" || zcompile "$f"; done'
    try:
        proc = subprocess.run(
            ["zsh", "-f", "-c", cmd],
            capture_output=True,
            text=True,
            timeout=timeout_s,
        )
        stderr = (proc.stderr or "").strip()
    except subprocess.TimeoutExpired:
        for f in existing:
            result["errors"].append((f, f"zcompile timeout after {timeout_s}s"))
        return result
    except Exception as e:
        for f in existing:
            result["errors"].append((f, str(e)))
        return result

    for f in existing:
        zwc = Path(f + ".zwc")
        if zwc.is_file():
            result["compiled"].append(f)
        else:
            msg = stderr.split("\n")[0] if stderr else "no .zwc produced"
            result["errors"].append((f, msg))
    return result


def compile_eager_artifacts(
    manifest: dict[str, Any],
    ziro_home: str | None = None,
    timeout_s: int = 30,
) -> dict[str, Any]:
    """Compile all eager artifacts to .zwc based on manifest.
    For eval-cache tools: compile cache_path.
    For source tools: compile path.
    Returns aggregate result dict.
    """
    paths = get_paths()
    if ziro_home is not None:
        paths["home"] = Path(ziro_home).resolve()

    files_to_compile: list[str] = []
    for tool in manifest.get("tool", []):
        if tool.get("timing") != "eager":
            continue
        method = tool.get("method", "")
        raw_path = ""
        if method == "eval-cache":
            raw_path = tool.get("cache_path", "")
        elif method == "source":
            raw_path = tool.get("path", "")

        if not raw_path:
            continue

        expanded = (
            raw_path.replace("${ZIRO_DATA}", str(paths["data"]))
            .replace("${ZIRO_CACHE}", str(paths["cache"]))
            .replace("${ZIRO_CONFIG}", str(paths["config"]))
            .replace("${ZIRO_HOME}", str(paths["home"]))
            .replace("$ZIRO_DATA", str(paths["data"]))
            .replace("$ZIRO_CACHE", str(paths["cache"]))
            .replace("$ZIRO_CONFIG", str(paths["config"]))
            .replace("$ZIRO_HOME", str(paths["home"]))
        )
        expanded = os.path.expandvars(os.path.expanduser(expanded))
        if expanded not in files_to_compile:
            files_to_compile.append(expanded)

        # Also compile in ziro_home/vendor if present
        if method == "source" and str(paths["data"] / "vendor") in expanded:
            alt = expanded.replace(str(paths["data"] / "vendor"), str(paths["home"] / "vendor"))
            if Path(alt).is_file() and alt not in files_to_compile:
                files_to_compile.append(alt)

    return _run_zcompile(files_to_compile, timeout_s=timeout_s)


def _validate_zwc_freshness(manifest: dict[str, Any], strict: bool = True) -> dict[str, Any]:
    """Validate that every eager artifact has a fresh .zwc sibling.

    Rule (Section 4 closeout): everything in ziro must be compiled after install/sync.
    For each eager tool (eval-cache or source), check:
      - <path>.zwc exists
      - <path>.zwc mtime > <path> mtime

    strict=True  -> raise ValueError if any fail (build fails)
    strict=False -> return dict with 'missing', 'stale', 'ok' lists (warn only)
    """
    import os
    from pathlib import Path as _P

    try:
        paths = get_paths()
    except Exception:
        paths = {}

    failures: dict[str, list[Any]] = {"missing": [], "stale": [], "ok": []}
    for tool in manifest.get("tool", []):
        if tool.get("timing") != "eager":
            continue
        method = tool.get("method", "")
        if method == "eval-cache":
            target = tool.get("cache_path", "")
        elif method == "source":
            target = tool.get("path", "")
        else:
            continue
        if not target:
            continue

        if paths:
            target = (
                target.replace("${ZIRO_DATA}", str(paths.get("data", "")))
                .replace("${ZIRO_CACHE}", str(paths.get("cache", "")))
                .replace("${ZIRO_CONFIG}", str(paths.get("config", "")))
                .replace("${ZIRO_HOME}", str(paths.get("home", "")))
                .replace("$ZIRO_DATA", str(paths.get("data", "")))
                .replace("$ZIRO_CACHE", str(paths.get("cache", "")))
                .replace("$ZIRO_CONFIG", str(paths.get("config", "")))
                .replace("$ZIRO_HOME", str(paths.get("home", "")))
            )
        tpath = _P(os.path.expandvars(os.path.expanduser(target)))
        if not tpath.is_file():
            # Check vendor fallback if source method
            alt_found = False
            if paths and method == "source" and str(paths.get("data", "") / "vendor") in str(tpath):
                alt = _P(str(tpath).replace(str(paths["data"] / "vendor"), str(paths["home"] / "vendor")))
                if alt.is_file():
                    tpath = alt
                    alt_found = True
            if not alt_found and not tpath.is_file():
                failures["missing"].append((str(tpath), "source file missing"))
                continue

        zwc = _P(str(tpath) + ".zwc")
        if not zwc.is_file():
            failures["missing"].append((str(tpath), "missing .zwc"))
            continue
        try:
            if zwc.stat().st_mtime <= tpath.stat().st_mtime:
                failures["stale"].append((str(tpath), "stale: zwc older than source"))
                continue
        except OSError as e:
            failures["stale"].append((str(tpath), str(e)))
            continue
        failures["ok"].append(str(tpath))

    total_bad = len(failures["missing"]) + len(failures["stale"])
    if total_bad and strict:
        lines = [f"  {p}: {m}" for p, m in failures["missing"] + failures["stale"]]
        msg = (
            f"strict zwc validation failed: {total_bad} eager file(s) not compiled.\n"
            + "\n".join(lines)
            + "\nRun `ziro sync` to compile. Use --no-strict-zwc to override (debug only)."
        )
        raise ValueError(msg)
    return failures


def write_boot_shim(boot_zsh_path: Path, paths: dict[str, Path] | None = None) -> Path:
    """Write the boot shim with baked runtime paths."""
    boot_zsh_path.parent.mkdir(parents=True, exist_ok=True)
    content = render_boot_shim(paths)
    boot_zsh_path.write_text(content, encoding="utf-8")
    return boot_zsh_path


def build(
    load_toml_path: Path | None = None,
    force: bool = False,
    rebuild_eval_caches: bool = False,
    strict_zwc: bool = False,
) -> tuple[bool, str, dict[str, int]]:
    """Execute the complete build pipeline."""
    paths = get_paths()
    if load_toml_path is None:
        load_toml_path = paths["config"] / "load.toml"

    # Step 1: Load manifest
    try:
        manifest = load_manifest(load_toml_path)
    except Exception as e:
        return False, f"Error parsing {load_toml_path}: {e}", {}

    # Step 2: Validate manifest
    errors = validate_manifest(manifest)
    if errors:
        return False, f"Validation failed ({len(errors)} errors):\n" + "\n".join(f"- {e}" for e in errors), {}

    # Step 3: Apply user overrides
    user_section = manifest.get("user")
    external_override = paths["config"] / "override.toml"
    tools = manifest.get("tool", [])
    merged_tools = apply_overrides(tools, user_section, external_override)

    # Resolve defer root
    defer_root = paths["home"] / "vendor" / "ziro-defer"
    if not defer_root.is_dir():
        cand = paths["home"] / "ziro-defer"
        if cand.is_dir():
            defer_root = cand

    # Rebuild eval caches if starship is installed
    if rebuild_eval_caches:
        eval_cache_dir = paths["cache"] / "eval-cache"
        eval_cache_dir.mkdir(parents=True, exist_ok=True)
        try:
            r = subprocess.run(["starship", "init", "zsh", "--print-full-init"], capture_output=True, text=True, timeout=5)
            if r.returncode == 0:
                (eval_cache_dir / "starship.zsh").write_text(r.stdout, encoding="utf-8")
        except Exception:
            pass

    # Step 4: Render ziro-boot.zsh
    boot_content = render_boot_script(manifest, merged_tools, defer_root)

    # Step 5: Write ziro-boot.zsh atomically
    boot_artifact = paths["cache"] / "ziro-boot.zsh"
    boot_artifact.parent.mkdir(parents=True, exist_ok=True)

    with tempfile.NamedTemporaryFile("w", dir=str(paths["cache"]), delete=False, encoding="utf-8") as tf:
        tf.write(boot_content)
        tmp_name = tf.name

    os.replace(tmp_name, str(boot_artifact))

    # Step 6: Compile .zwc
    ok, err = compile_zwc(boot_artifact)
    if not ok:
        return False, f"zcompile failed: {err}", {}

    # Precompile all eager artifacts (idempotent; safe to re-run)
    try:
        compile_result = compile_eager_artifacts(manifest)
        if compile_result.get("compiled"):
            print(f"[precompile] compiled {len(compile_result['compiled'])} eager artifacts")
        if compile_result.get("errors"):
            for path, msg in compile_result["errors"]:
                print(f"[precompile] WARN: {path}: {msg}")
    except Exception as e:
        print(f"[precompile] WARN: compilation step failed: {e}")

    # Section-4 rule: everything compiled. Fail build on missing/stale .zwc.
    try:
        _validate_zwc_freshness(manifest, strict=strict_zwc)
    except ValueError as e:
        return False, str(e), {}

    # Step 7: Write boot.zsh shim
    write_boot_shim(paths["config"] / "boot.zsh", paths=paths)

    # Step 8: Verify boot script loads cleanly
    test_cmd = f"source '{boot_artifact}'; exit 0"
    r_test = subprocess.run(
        ["zsh", "-f", "-c", test_cmd],
        capture_output=True,
        text=True,
        timeout=10,
    )
    if r_test.returncode != 0:
        return False, f"Boot verification failed: {r_test.stderr.strip()}", {}

    # Counts
    eager_count = sum(1 for t in merged_tools if t.get("timing") == "eager" and t.get("enabled", True))
    def_count = sum(1 for t in merged_tools if t.get("timing") == "deferred" and t.get("enabled", True))
    ondemand_count = sum(1 for t in merged_tools if t.get("timing") == "on-demand" and t.get("enabled", True))
    counts = {"eager": eager_count, "deferred": def_count, "on_demand": ondemand_count}

    summary = (
        f"Synced: {eager_count} eager, {def_count} deferred, {ondemand_count} on-demand tools.\n"
        f"Artifact: {boot_artifact} (.zwc compiled)\n"
        f"Shim: {paths['config'] / 'boot.zsh'}"
    )
    return True, summary, counts


def main(argv: list[str] | None = None) -> int:
    """CLI entrypoint for ziro sync."""
    args = list(argv or sys.argv[1:])
    rebuild = "--rebuild-caches" in args
    force = "--force" in args
    strict_zwc = "--no-strict-zwc" not in args
    if not strict_zwc:
        print("ziro sync: strict=off: compiled-only rule relaxed", file=sys.stderr)
    config_path = None
    if "--config" in args:
        idx = args.index("--config")
        if idx + 1 < len(args):
            config_path = Path(args[idx + 1]).resolve()

    ok, msg, counts = build(
        load_toml_path=config_path,
        rebuild_eval_caches=rebuild,
        force=force,
        strict_zwc=strict_zwc,
    )
    if not ok:
        print(f"ziro sync: error: {msg}", file=sys.stderr)
        return 1

    print(f"✔ {msg}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
