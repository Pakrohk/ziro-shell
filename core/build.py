def _shell_path(p: str) -> str:
    """Format path for Zsh emission inside double quotes.

    Replaces leading `~` with `$HOME` so that `"$HOME/..."` expands cleanly
    at source time in Zsh (since `"~"` inside quotes is not tilde-expanded by POSIX/Zsh).
    """
    if p.startswith("~/"):
        return "$HOME/" + p[2:]
    if p == "~":
        return "$HOME"
    return p


def _filter_resolved(tools: list[dict[str, Any]]) -> tuple[list[dict[str, Any]], list[str]]:
    """Split tools into (resolved, unresolved_names). Used by render to skip
    tools whose path is not on disk (avoid runtime source errors)."""
    resolved: list[dict[str, Any]] = []
    unresolved: list[str] = []
    for t in tools:
        if t.get("unresolved") is True:
            unresolved.append(t.get("name", "?"))
        else:
            resolved.append(t)
    return resolved, unresolved


def render_eager_section(tools: list[dict[str, Any]]) -> str:
    """Render Section 2: Eager tools."""
    eager_tools = [t for t in tools if t.get("timing") == "eager" and t.get("enabled", True)]
    eager_tools.sort(key=lambda t: t.get("order", 100))

    lines: list[str] = [
        "# --- Section 2: Eager tools ---",
        "if (( ! $+functions[compdef] )); then",
        "  typeset -ga _ziro_compdef_queue=()",
        '  compdef() { _ziro_compdef_queue+=("${(j: :)${(q-)@}}"); }',
        "fi",
    ]

    # Collect fpath additions
    all_fpaths: list[str] = []
    for t in eager_tools:
        fps = t.get("fpath", [])
        if isinstance(fps, list):
            for fp in fps:
                if fp not in all_fpaths:
                    all_fpaths.append(fp)

    if all_fpaths:
        quoted = " ".join(f'"{_shell_path(fp)}"' for fp in all_fpaths)
        lines.append(f"fpath=({quoted} $fpath)")

    for t in eager_tools:
        if t.get("unresolved") is True:
            continue
        name = t.get("name", "")
        method = t.get("method")
        path = _shell_path(t.get("path", ""))
        cache_path = _shell_path(t.get("cache_path", ""))
        post_source = t.get("post_source", "")

        if method == "builtin":
            if name == "compinit":
                lines.append('autoload -Uz compinit && compinit -C -d "${ZIRO_CACHE}/zcompdump"')
                lines.append('if (( $+_ziro_compdef_queue )); then')
                lines.append('  for _cd in "$_ziro_compdef_queue[@]"; do eval "compdef $_cd"; done')
                lines.append('  unset _ziro_compdef_queue _cd')
                lines.append('fi')
        elif method == "source" and path:
            lines.append(f'source "{path}"')
        elif method == "eval-cache" and cache_path:
            lines.append(f'[[ -f "{cache_path}" ]] && source "{cache_path}"')

        if post_source:
            lines.append(post_source)

    return "\n".join(lines)


def render_deferred_section(tools: list[dict[str, Any]]) -> str:
    """Render Section 3: Deferred tasks.
    
    Guarantees syntax_highlighting plugins always sort last to prevent
    ZLE widget wrapping desynchronization on any present or future plugin.
    """
    def_tools = [t for t in tools if t.get("timing") == "deferred" and t.get("enabled", True)]

    def _deferred_sort_key(t: dict[str, Any]) -> tuple[int, int]:
        is_syntax = 1 if (
            t.get("category") == "syntax_highlighting"
            or "syntax-highlighting" in t.get("name", "")
        ) else 0
        return (is_syntax, t.get("order", 100))

    def_tools.sort(key=_deferred_sort_key)

    lines: list[str] = ["# --- Section 3: Deferred tasks ---"]

    for t in def_tools:
        if t.get("unresolved") is True:
            continue
        stage = t.get("stage", 5)
        slot = t.get("slot", "b")
        path = _shell_path(t.get("path", ""))
        name = t.get("name", "")
        if path:
            name_flag = f'--name="{name}" ' if name else ""
            lines.append(f'ziro-defer --stage={stage} --slot={slot} {name_flag}source "{path}"')

    return "\n".join(lines)


def render_ondemand_section(tools: list[dict[str, Any]]) -> str:
    """Render Section 4: On-demand proxies."""
    od_tools = [t for t in tools if t.get("timing") == "on-demand" and t.get("enabled", True)]
    od_tools.sort(key=lambda t: t.get("order", 100))

    lines: list[str] = ["# --- Section 4: On-demand proxies ---"]

    for t in od_tools:
        if t.get("unresolved") is True:
            continue
        name = t.get("name", "")
        trigger = t.get("trigger", "")
        path = t.get("path", "")
        cache_path = t.get("cache_path", "")
        target_path = _shell_path(cache_path or path)

        if trigger == "key":
            trigger_keys = t.get("trigger_keys", [])
            slug = name.replace("-", "_")
            loader_fn = f"_ziro_{slug}_load"
            lines.append(f"{loader_fn}() {{")
            lines.append(f'  [[ -n "${{_ZIRO_{slug.upper()}_LOADED:-}}" ]] && return 0')
            lines.append(f'  source "{target_path}" || return 1')
            lines.append(f"  typeset -g _ZIRO_{slug.upper()}_LOADED=1")
            lines.append("  (( $+functions[_zsh_highlight_bind_widgets] )) && _zsh_highlight_bind_widgets 2>/dev/null || true")
            lines.append("}")

            for kdef in trigger_keys:
                if isinstance(kdef, dict):
                    k = kdef.get("key", "")
                    w = kdef.get("widget", "")
                    lines.append(f"ziro-defer-bind-widget '{k}' '{loader_fn}; zle {w}'")
                elif isinstance(kdef, str):
                    lines.append(f"ziro-defer-bind-widget '{kdef}' '{loader_fn}'")

        elif trigger == "command":
            cmds = t.get("trigger_commands", [])
            slug = name.replace("-", "_")
            proxy_fn = f"_ziro_proxy_{slug}"
            cmd_list = " ".join(cmds)
            lines.append(f"{proxy_fn}() {{")
            lines.append('  local _target_cmd="$1"; shift')
            lines.append(f"  unfunction {proxy_fn} {cmd_list} 2>/dev/null")
            lines.append(f'  source "{target_path}"')
            lines.append('  "$_target_cmd" "$@"')
            lines.append("}")
            for cmd in cmds:
                lines.append(f'{cmd}() {{ {proxy_fn} "$0" "$@"; }}')

        elif trigger == "function":
            funcs = t.get("trigger_functions", [])
            slug = name.replace("-", "_")
            proxy_fn = f"_ziro_proxy_{slug}"
            func_list = " ".join(funcs)
            lines.append(f"{proxy_fn}() {{")
            lines.append('  local _target_cmd="$1"; shift')
            lines.append(f"  unfunction {proxy_fn} {func_list} 2>/dev/null")
            lines.append(f'  source "{target_path}"')
            lines.append('  "$_target_cmd" "$@"')
            lines.append("}")
            for fn in funcs:
                lines.append(f'{fn}() {{ {proxy_fn} "$0" "$@"; }}')

    return "\n".join(lines)


