HEADER_LINE = "# AUTO-GENERATED by ziro — do not edit"
SCHEMA_VERSION = "0.1.0"
_TOOLS_FACTORY_FILE = Path(__file__).resolve().parent / "tools_factory.toml"


@dataclass(frozen=True)
class EmitOptions:
    """Options for generator."""
    enforce_order: bool = True
    generated_at: str = ""
    ziro_home: Path | None = None


def load_tools_registry(config_dir: Path | None = None) -> list[dict[str, Any]]:
    """Load tools registry from tools_factory.toml and optional user overrides."""
    tools: list[dict[str, Any]] = []
    if _TOOLS_FACTORY_FILE.is_file():
        try:
            with _TOOLS_FACTORY_FILE.open("rb") as f:
                data = tomllib.load(f)
                tools = data.get("tool", [])
        except Exception:
            tools = []

    if config_dir is not None:
        user_tools_file = config_dir / "tools.toml"
        if user_tools_file.is_file():
            try:
                with user_tools_file.open("rb") as f:
                    u_data = tomllib.load(f)
                    u_tools = u_data.get("tool", [])
                    if u_tools:
                        tool_map = {t["name"]: t for t in tools if "name" in t}
                        for ut in u_tools:
                            if "name" in ut:
                                tool_map[ut["name"]] = ut
                        tools = list(tool_map.values())
            except Exception:
                pass

    return tools


def emit_on_demand_key(tool: dict) -> str:
    """Emit on-demand trigger for key-bound tools (fzf).
    Once any trigger fires, sources cache; subsequent fires dispatch widget.
    """
    name = tool.get("name", "")
    cache_key = tool.get("cache_key", name)
    binary = tool.get("requires", name)
    keys = tool.get("trigger_keys", [])
    guard = f"_ZIRO_{cache_key.upper()}_LOADED"
    load_fn = f"_ziro_{cache_key}_load"
    lines = [f"# {name} — on-demand (key triggers)",
             f"if (( $+commands[{binary}] )); then",
             f"  {load_fn}() {{",
             f"    [[ -n \"${{{guard}:-}}\" ]] && return 0",
             f"    source ~/.cache/ziro/eval-cache/{cache_key}.zsh || return 1",
             f"    typeset -g {guard}=1",
             f"  }}"]
    for k in keys:
        lines.append(f"  ziro-defer-bind-widget '{k.get('key','')}' '{load_fn}; zle {k.get('widget','')}'")
    lines.append("fi")
    return "\n".join(lines) + "\n"


def emit_on_demand_command(tool: dict) -> str:
    """Emit on-demand command proxies (zoxide, wd).
    First call sources; subsequent calls direct dispatch.
    """
    name = tool.get("name", "")
    cache_key = tool.get("cache_key", name)
    binary = tool.get("requires", "")
    cmds = tool.get("trigger_commands", [])
    source_path = tool.get("source", f"~/.cache/ziro/eval-cache/{cache_key}.zsh")
    guard = f"_ZIRO_{cache_key.upper()}_LOADED"
    ensure = f"_ziro_{cache_key}_ensure"
    lines = [f"# {name} — on-demand (command proxies)"]
    indent = "  " if binary else ""
    if binary:
        lines.append(f"if (( $+commands[{binary}] )); then")
    lines.extend([
        f"{indent}{ensure}() {{",
        f"{indent}  local _fn=\"$1\"; shift",
        f"{indent}  if [[ -z \"${{{guard}:-}}\" ]]; then",
        f"{indent}    source {source_path} || return 1",
        f"{indent}    typeset -g {guard}=1",
        f"{indent}  fi",
        f"{indent}  \"$_fn\" \"$@\"",
        f"{indent}}}",
    ])
    for c in cmds:
        lines.append(f"{indent}{c}() {{ {ensure} {c} \"$@\"; }}")
    if binary:
        lines.append("fi")
    return "\n".join(lines) + "\n"


def emit_on_demand_function(tool: dict) -> str:
    """Emit on-demand function proxies (helpers).
    First call to ANY function sources; subsequent calls direct dispatch.
    Each function has its own proxy that un-functions itself on first call.
    """
    name = tool.get("name", "")
    cache_key = tool.get("cache_key", name)
    fns = tool.get("trigger_functions", [])
    source_path = tool.get("source", f"$ZIRO_HOME/lib/{cache_key}.zsh")
    clean_key = cache_key.replace("ziro-", "").replace("-", "_")
    guard = f"_ZIRO_{clean_key.upper()}_LOADED"
    ensure = f"_ziro_{clean_key}_ensure"
    lines = [f"# {name} — on-demand (function proxies)",
             f"{ensure}() {{",
             f"  [[ -n \"${{{guard}:-}}\" ]] && return 0",
             f"  source {source_path}",
             f"  typeset -g {guard}=1",
             f"  typeset -g _ZIRO_ZIRO_HELPERS_LOADED=1",
             f"}}"]
    for fn in fns:
        lines.append(f"{fn}() {{ unfunction {fn}; {ensure}; {fn} \"$@\"; }}")
    return "\n".join(lines) + "\n"


def emit_pattern(tool: dict[str, Any]) -> str:
    """Emit zsh shell command string for a declarative tool registry entry."""
    method = tool.get("load_method", "")
    timing = tool.get("load_timing", "")

    if timing == "on-demand":
        tt = tool.get("trigger_type", "")
        if tt == "key":
            return emit_on_demand_key(tool)
        elif tt == "command":
            return emit_on_demand_command(tool)
        elif tt == "function":
            return emit_on_demand_function(tool)

    if method == "bootstrap-source":
        return f"source {tool['source']}"

    if method == "builtin-load":
        return tool.get("name", "")

    if method == "clone-source":
        repo = tool.get("source", "")
        if tool.get("subpath"):
            repo = f"{repo} {tool['subpath']}"
        base = f"znap source {repo}"
        return wrap_timing(base, timing)

    if method == "clone-eval":
        return f'znap eval {tool["source"]} "{tool.get("eval_command", "")}"'

    if method == "binary-eval":
        guard = f"(( $+commands[{tool['binary_name']}] )) && " if tool.get("guard") == "binary-check" else ""
        cmd = f"znap eval {tool.get('cache_key', '')} '{tool.get('init_command', '')}'"
        return f"{guard}{cmd}"

    if method == "local-source":
        base = f"source {tool.get('local_path', '')}"
        return wrap_timing(base, timing)

    raise ValueError(f"Unknown load_method: {method!r} for tool {tool.get('name')!r}")


def wrap_timing(cmd: str, timing: str) -> str:
    """Wrap command with ziro-defer if timing is defer."""
    if timing == "defer":
        return f"ziro-defer {cmd}"
    return cmd


def _resolve_plugin_target(plugin: str, pick: str = "", ziro_home: Path | None = None) -> tuple[str, bool]:
    """Detect if plugin is a local clone in plugins/.

    Returns (target_string, is_local).
    """
    if plugin.startswith(("$ZIRO_HOME/", "~/.ziro/", "plugins/")):
        return plugin, True

    zh = ziro_home or Path(os.environ.get("ZIRO_HOME", Path.home() / ".ziro"))
    pdir = zh / "plugins" / plugin
    if not pdir.is_dir():
        rel_pdir = Path("plugins") / plugin
        if rel_pdir.is_dir():
            pdir = rel_pdir
        else:
            return plugin, False

    if pick and (pdir / pick).is_file():
        return f"$ZIRO_HOME/plugins/{plugin}/{pick}", True

    cand = pdir / f"{plugin}.plugin.zsh"
    if cand.is_file():
        return f"$ZIRO_HOME/plugins/{plugin}/{cand.name}", True

    named = list(pdir.glob(f"**/{plugin}.plugin.zsh"))
    if named:
        rel = named[0].relative_to(pdir)
        return f"$ZIRO_HOME/plugins/{plugin}/{rel}", True

    cand_zsh = pdir / f"{plugin}.zsh"
    if cand_zsh.is_file():
        return f"$ZIRO_HOME/plugins/{plugin}/{cand_zsh.name}", True

    return f"$ZIRO_HOME/plugins/{plugin}", True


def _emit_plugin(
    plugin: str,
    strategy: str,
    *,
    compile_: bool = True,
    eval_cache: bool = False,
    pick: str = "",
    defer_slot: str = "",
    raw: str = "",
    ziro_home: Path | None = None,
    stage: int = 5,
    slot: str = "b",
    name: str = "",
    depends: tuple[str, ...] = (),
    condition: Optional[str] = None,
    on_key: Optional[str] = None,
    cache_type: str = "none",
    timeout_ms: Optional[int] = None,
) -> str:
    """Emit zsh line for one plugin via ziro_load."""
    target_plugin, is_local = _resolve_plugin_target(plugin, pick=pick, ziro_home=ziro_home)
    spec = from_resolved(
        plugin=target_plugin,
        strategy=strategy,
        compile_=compile_,
        eval_cache=eval_cache,
        pick="" if is_local else pick,
        defer_slot=defer_slot,
        raw=raw,
        is_local=is_local,
        stage=stage,
        slot=slot,
        name=name,
        depends=depends,
        condition=condition,
        on_key=on_key,
        cache_type=cache_type,
        timeout_ms=timeout_ms,
    )
    return emit(spec)


def generate(
    configs: list,  # list[ResolvedConfig]
    output_path: Path,
    *,
    options: EmitOptions | None = None,
) -> Path:
    """Write plugins.gen.zsh (Schema C). Deterministic for same input."""
    opts = options or EmitOptions()
    ts = opts.generated_at or datetime.now(timezone.utc).isoformat()

    ordered = list(configs)
    if opts.enforce_order:
        tools = load_tools_registry()
        tool_order_map: dict[str, int] = {}
        for t in tools:
            t_name = t.get("name")
            if t_name and not t.get("alternatives_only", False):
                tool_order_map[t_name] = t.get("load_order", 999)

        def order_key(cfg: Any) -> int:
            plugin_name = getattr(cfg, "plugin", "")
            if plugin_name in tool_order_map:
                return tool_order_map[plugin_name]
            omz_name = f"ohmyzsh-{plugin_name}"
            if omz_name in tool_order_map:
                return tool_order_map[omz_name]
            return 999

        ordered = sorted(configs, key=order_key)

    lines: list[str] = [
        HEADER_LINE,
        f"# Schema: {SCHEMA_VERSION}",
        f"# Generated: {ts}",
        "",
    ]

    for cfg in ordered:
        line = _emit_plugin(
            plugin=cfg.plugin,
            strategy=cfg.strategy.value if hasattr(cfg.strategy, "value") else str(cfg.strategy),
            compile_=getattr(cfg, "compile", True),
            eval_cache=getattr(cfg, "eval_cache", False),
            pick=getattr(cfg, "pick", ""),
            defer_slot=getattr(cfg, "defer_slot", ""),
            raw=getattr(cfg, "raw", ""),
            ziro_home=opts.ziro_home,
            stage=getattr(cfg, "stage", 5),
            slot=getattr(cfg, "slot", "b"),
            name=getattr(cfg, "name", ""),
            depends=getattr(cfg, "depends", ()),
            condition=getattr(cfg, "condition", None),
            on_key=getattr(cfg, "on_key", None),
            cache_type=getattr(cfg, "cache_type", "none"),
            timeout_ms=getattr(cfg, "timeout_ms", None),
        )
        lines.append(line)

    lines.append("")

    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text("\n".join(lines))
    return output_path


def generate_plugins_gen(
    config_dir: Path,
    ziro_home: Path | None = None,
) -> Path:
    """Generate ~/.config/ziro/derived/plugins.gen.zsh from defaults.toml and declarative registry.

    Implements Spec 001 FR-006a (materialized at generation time) and Spec 006 (Declarative Registry).
    """
    zh = ziro_home or Path(os.environ.get("ZIRO_HOME", Path.home() / ".ziro"))
    configs: list[ResolvedConfig] = []

    # 1. Parse selections from defaults.toml (seeded from factory defaults)
    tools = load_tools_registry(config_dir)
    sorted_tools = sorted(tools, key=lambda t: t.get("load_order", 999))

    # Seed active selections with factory defaults for configurable categories
    active_selections: dict[str, str] = {}
    for t in sorted_tools:
        cat = t.get("category", "")
        if not t.get("alternatives_only", False) and cat not in ("core", "infra"):
            active_selections[cat] = t.get("name", "")

    defaults_file = config_dir / "defaults.toml"
    defaults_data: dict[str, Any] = {}
    if defaults_file.is_file():
        try:
            with defaults_file.open("rb") as f:
                defaults_data = tomllib.load(f)
        except Exception:
            pass

    # Override active selections with user configuration from defaults.toml
    for category_name, category_cfg in defaults_data.items():
        if isinstance(category_cfg, dict) and "default" in category_cfg:
            active_selections[category_name] = category_cfg["default"]

    # Allow prompt.conf to override prompt category selection
    prompt_conf_file = config_dir / "prompt.conf"
    if prompt_conf_file.is_file():
        try:
            p_val = prompt_conf_file.read_text(encoding="utf-8").strip()
            if p_val:
                active_selections["prompt"] = p_val
        except OSError:
            pass

    selected_tool_names = set(active_selections.values())

    # 2. Iterate declarative tools registry
    for tool in sorted_tools:
        # Skip infrastructure and builtin markers in plugins.gen.zsh
        if tool.get("type") in ("bootstrap", "builtin"):
            continue

        tool_category = tool.get("category", "")
        tool_name = tool.get("name", "")
        timing = tool.get("load_timing", "")

        # Core tools emit by default unless marked alternatives_only
        if tool_category == "core":
            if tool.get("alternatives_only", False) and tool_name not in selected_tool_names:
                continue
        elif timing == "on-demand":
            pass
        else:
            if tool_category not in active_selections:
                continue
            if tool_name not in selected_tool_names:
                continue

        if timing == "on-demand":
            tt = tool.get("trigger_type", "")
            if tt == "key":
                raw_line = emit_on_demand_key(tool)
            elif tt == "command":
                raw_line = emit_on_demand_command(tool)
            elif tt == "function":
                raw_line = emit_on_demand_function(tool)
            else:
                raw_line = emit_pattern(tool)
        else:
            raw_line = emit_pattern(tool)
        timing = tool.get("load_timing", "")
        configs.append(
            ResolvedConfig(
                plugin=tool_name,
                strategy=Strategy.AFTER_PROMPT if timing == "defer" else Strategy.EAGER,
                eval_cache=timing == "eval",
                raw=raw_line,
            )
        )

    # 3. Add local plugins in $ZIRO_HOME/plugins/
    pdir = zh / "plugins"
    if pdir.is_dir():
        from core.analyzer import analyze_with_cache
        from core.resolver import resolve
        known_factory_names = {t.get("name") for t in tools}
        for p in sorted(pdir.iterdir()):
            if p.is_dir() and not p.name.startswith("."):
                if p.name in known_factory_names or f"ohmyzsh-{p.name}" in known_factory_names:
                    continue
                try:
                    analysis = analyze_with_cache(p, p.name)
                    configs.append(resolve(analysis, config_dir))
                except Exception:
                    continue

    output_path = default_output_path(config_dir)
    return generate(configs, output_path, options=EmitOptions(enforce_order=True, ziro_home=zh))


def default_output_path(config_dir: Path) -> Path:
    return config_dir / "derived" / "plugins.gen.zsh"


